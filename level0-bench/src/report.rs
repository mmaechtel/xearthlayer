//! Turns benchmark rows into `results.csv`, `summary.md`, crops and the
//! HTML contact sheet.

use crate::metrics::Scores;
use crate::variants::VARIANTS;
use image::{Rgba, RgbaImage};
use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::fs;
use std::path::Path;

/// One tile under one variant.
#[derive(Debug, Clone)]
pub struct Row {
    pub provider: String,
    pub location: String,
    pub content: String,
    pub synthetic: bool,
    pub quality: Option<u8>,
    pub subsampling: Option<String>,
    /// Index into [`VARIANTS`].
    pub variant: usize,
    /// Scores of the filtered level 0 before BC1.
    pub pre: Scores,
    /// Scores after XEL's BC1 encode and a decode: what the sim shows.
    pub post: Scores,
    /// Filter time scaled to a 4096 x 4096 tile, in milliseconds.
    pub filter_ms: f64,
    /// BC1 level 0 encode time scaled to a 4096 x 4096 tile.
    pub bc1_ms: f64,
}

fn mean(values: &[f64]) -> f64 {
    values.iter().sum::<f64>() / values.len().max(1) as f64
}

fn median(values: &[f64]) -> f64 {
    let mut sorted = values.to_vec();
    sorted.sort_by(f64::total_cmp);
    match sorted.len() {
        0 => f64::NAN,
        n if n % 2 == 1 => sorted[n / 2],
        n => (sorted[n / 2 - 1] + sorted[n / 2]) / 2.0,
    }
}

/// Rows grouped by tile, each group ordered by variant index.
fn by_tile(rows: &[Row]) -> Vec<Vec<&Row>> {
    let mut groups: BTreeMap<(&str, &str), Vec<&Row>> = BTreeMap::new();
    for row in rows {
        groups
            .entry((&row.provider, &row.location))
            .or_default()
            .push(row);
    }
    groups
        .into_values()
        .map(|mut g| {
            g.sort_by_key(|r| r.variant);
            g
        })
        .collect()
}

/// For the tiles `keep` selects: per variant, the per-tile differences to
/// the baseline of `value`.
fn deltas(rows: &[Row], keep: impl Fn(&Row) -> bool, value: impl Fn(&Row) -> f64) -> Vec<Vec<f64>> {
    let mut out = vec![Vec::new(); VARIANTS.len()];
    for tile in by_tile(rows) {
        if !keep(tile[0]) {
            continue;
        }
        let base = value(tile[0]);
        for row in tile {
            out[row.variant].push(value(row) - base);
        }
    }
    out
}

fn providers(rows: &[Row]) -> Vec<String> {
    let mut names: Vec<String> = rows.iter().map(|r| r.provider.clone()).collect();
    names.sort();
    names.dedup();
    names
}

/// The variant with the highest mean SSIM after BC1 for a provider.
pub fn best_variant(rows: &[Row], provider: &str) -> usize {
    let d = deltas(rows, |r| r.provider == provider, |r| r.post.ssim);
    (0..VARIANTS.len())
        .max_by(|&a, &b| mean(&d[a]).total_cmp(&mean(&d[b])))
        .unwrap_or(0)
}

pub fn write_csv(rows: &[Row], path: &Path) -> std::io::Result<()> {
    let mut out = String::from(
        "provider,location,content,variant,ssim_pre,ssim_linear_pre,psnr_pre,butteraugli_pre,\
         ssim_post,ssim_linear_post,psnr_post,butteraugli_post\n",
    );
    for r in rows {
        let _ = writeln!(
            out,
            "{},{},{},{},{:.6},{:.6},{:.3},{:.4},{:.6},{:.6},{:.3},{:.4}",
            r.provider,
            r.location,
            r.content,
            VARIANTS[r.variant].name,
            r.pre.ssim,
            r.pre.ssim_linear,
            r.pre.psnr,
            r.pre.butteraugli,
            r.post.ssim,
            r.post.ssim_linear,
            r.post.psnr,
            r.post.butteraugli,
        );
    }
    fs::write(path, out)
}

/// The generated part of `summary.md`. Timings are left out of the CSV and
/// rounded here because they are the only values that differ between runs.
pub fn summary(rows: &[Row], notes: &str) -> String {
    let mut s = String::new();
    let names = providers(rows);
    let tiles = by_tile(rows);
    let synthetic = rows.iter().all(|r| r.synthetic);
    let _ = writeln!(s, "# Level 0 sharpening benchmark\n");
    let _ = writeln!(
        s,
        "Generated by `level0-bench run`. {} tiles, {} providers, {} variants. \
         Every number except the timings is deterministic.\n",
        tiles.len(),
        names.len(),
        VARIANTS.len()
    );
    if synthetic {
        let _ = writeln!(
            s,
            "> **The data is synthetic.** The sandbox this ran in blocks every tile server, so the \
             \"providers\" below are procedural scenes JPEG-encoded at several qualities. The numbers \
             show how the filters respond to JPEG quality and content. They are not measurements of \
             Bing, Google, ArcGIS, Apple or USGS. Run `scripts/level0-bench.sh real` on a machine \
             with network access for those.\n"
        );
    }

    let _ = writeln!(s, "## Dataset\n");
    let _ = writeln!(s, "| Provider | Tiles | JPEG quality (estimate) | Chroma | Baseline SSIM before BC1 | after BC1 | Baseline PSNR after BC1 |");
    let _ = writeln!(s, "|---|---|---|---|---|---|---|");
    for p in &names {
        let base: Vec<&Row> = rows
            .iter()
            .filter(|r| &r.provider == p && r.variant == 0)
            .collect();
        let mut q: Vec<u8> = base.iter().filter_map(|r| r.quality).collect();
        q.sort_unstable();
        let quality = match (q.first(), q.last()) {
            (Some(a), Some(b)) if a == b => a.to_string(),
            (Some(a), Some(b)) => format!("{a} to {b}"),
            _ => "?".to_string(),
        };
        let mut chroma: Vec<&str> = base
            .iter()
            .filter_map(|r| r.subsampling.as_deref())
            .collect();
        chroma.sort_unstable();
        chroma.dedup();
        let col = |f: fn(&Row) -> f64| mean(&base.iter().map(|r| f(r)).collect::<Vec<_>>());
        let _ = writeln!(
            s,
            "| {p} | {} | {quality} | {} | {:.4} | {:.4} | {:.2} dB |",
            base.len(),
            chroma.join(", "),
            col(|r| r.pre.ssim),
            col(|r| r.post.ssim),
            col(|r| r.post.psnr),
        );
    }

    let _ = writeln!(s, "\n## Results per provider\n");
    let _ = writeln!(
        s,
        "Differences to the baseline of the same tile, measured against the ZL18 truth. \
         SSIM and PSNR: higher is better. Butteraugli (3-norm): lower is better. \
         \"after BC1\" is the level 0 the sim shows; \"before BC1\" isolates what BC1 eats. \
         Time is the filter alone on one core, scaled to a 4096 x 4096 tile.\n"
    );
    for p in &names {
        let keep = |r: &Row| &r.provider == p;
        let ssim = deltas(rows, keep, |r| r.post.ssim);
        let lin = deltas(rows, keep, |r| r.post.ssim_linear);
        let psnr = deltas(rows, keep, |r| r.post.psnr);
        let butter = deltas(rows, keep, |r| r.post.butteraugli);
        let pre = deltas(rows, keep, |r| r.pre.ssim);
        let best = best_variant(rows, p);
        let _ = writeln!(s, "### {p}\n");
        let _ = writeln!(s, "| Variant | SSIM after BC1, mean | median | Linear-light SSIM, mean | PSNR, mean | Butteraugli, mean | SSIM before BC1, mean | Tiles better | Time |");
        let _ = writeln!(s, "|---|---|---|---|---|---|---|---|---|");
        for (i, v) in VARIANTS.iter().enumerate() {
            let times: Vec<f64> = rows
                .iter()
                .filter(|r| keep(r) && r.variant == i)
                .map(|r| r.filter_ms)
                .collect();
            let better = ssim[i].iter().filter(|d| **d > 0.0).count();
            let mark = if i == best && i != 0 {
                " **(best)**"
            } else {
                ""
            };
            let _ = writeln!(
                s,
                "| {}{mark} | {:+.4} | {:+.4} | {:+.4} | {:+.2} dB | {:+.3} | {:+.4} | {}/{} | {:.0} ms |",
                v.name,
                mean(&ssim[i]),
                median(&ssim[i]),
                mean(&lin[i]),
                mean(&psnr[i]),
                mean(&butter[i]),
                mean(&pre[i]),
                better,
                ssim[i].len(),
                median(&times),
            );
        }
        let _ = writeln!(s);
    }

    let mut contents: Vec<String> = rows.iter().map(|r| r.content.clone()).collect();
    contents.sort();
    contents.dedup();
    let _ = writeln!(s, "## Content types\n");
    let _ = writeln!(
        s,
        "Mean SSIM difference after BC1 per content type, one table per provider. \
         Bold is the best variant of the column; a negative number is a loss.\n"
    );
    for p in &names {
        let _ = writeln!(s, "### {p}\n");
        let _ = writeln!(s, "| Variant | {} |", contents.join(" | "));
        let _ = writeln!(s, "|---|{}", "---|".repeat(contents.len()));
        let per_content: Vec<Vec<f64>> = contents
            .iter()
            .map(|c| {
                deltas(
                    rows,
                    |r| &r.provider == p && &r.content == c,
                    |r| r.post.ssim,
                )
                .iter()
                .map(|d| mean(d))
                .collect()
            })
            .collect();
        for (i, v) in VARIANTS.iter().enumerate().skip(1) {
            let cells: Vec<String> = per_content
                .iter()
                .map(|column| {
                    let top = column.iter().copied().fold(f64::MIN, f64::max);
                    if column[i] == top && top > 0.0 {
                        format!("**{:+.4}**", column[i])
                    } else {
                        format!("{:+.4}", column[i])
                    }
                })
                .collect();
            let _ = writeln!(s, "| {} | {} |", v.name, cells.join(" | "));
        }
        let _ = writeln!(s);
    }

    let bc1: Vec<f64> = rows
        .iter()
        .filter(|r| r.variant == 0)
        .map(|r| r.bc1_ms)
        .collect();
    let _ = writeln!(s, "## Timing\n");
    let _ = writeln!(
        s,
        "Relative numbers only, from the machine the benchmark ran on ({} logical cores), not \
         from a flight PC. One core, scaled by pixel count to a 4096 x 4096 tile. For scale, the \
         BC1 encode of level 0 through XEL's ISPC path took a median of {:.0} ms per tile here. \
         The filters are plain scalar Rust with no SIMD or threading.\n",
        std::thread::available_parallelism().map_or(0, usize::from),
        median(&bc1)
    );
    if !notes.trim().is_empty() {
        let _ = writeln!(s, "{}", notes.trim());
    }
    s
}

/// A 256 pixel window of the truth with the most detail: the highest luma
/// variance on a 128 pixel grid.
pub fn busiest_window(truth: &RgbaImage) -> (u32, u32) {
    let luma = crate::metrics::luma(truth);
    let (w, h) = truth.dimensions();
    let mut best = ((0, 0), -1.0);
    for y in (0..=h - 256).step_by(128) {
        for x in (0..=w - 256).step_by(128) {
            let (mut sum, mut sq) = (0.0f64, 0.0f64);
            for j in y..y + 256 {
                for i in x..x + 256 {
                    let v = f64::from(luma[(j * w + i) as usize]);
                    sum += v;
                    sq += v * v;
                }
            }
            let n = 256.0 * 256.0;
            let variance = sq / n - (sum / n).powi(2);
            if variance > best.1 {
                best = ((x, y), variance);
            }
        }
    }
    best.0
}

/// The same 256 pixel window of three images side by side.
pub fn triptych(images: [&RgbaImage; 3], x: u32, y: u32) -> RgbaImage {
    const GAP: u32 = 8;
    let mut out = RgbaImage::from_pixel(3 * 256 + 2 * GAP, 256, Rgba([255, 255, 255, 255]));
    for (i, image) in images.iter().enumerate() {
        let crop = image::imageops::crop_imm(*image, x, y, 256, 256).to_image();
        image::imageops::replace(&mut out, &crop, i64::from(i as u32 * (256 + GAP)), 0);
    }
    out
}

/// One crop of the contact sheet.
pub struct Crop {
    pub provider: String,
    pub location: String,
    pub content: String,
    pub file: String,
    pub variant: usize,
    pub ssim_base: f64,
    pub ssim_best: f64,
}

pub fn contact_sheet(crops: &[Crop]) -> String {
    let mut s = String::from(
        "<!doctype html>\n<html lang=\"en\"><head><meta charset=\"utf-8\">\n\
         <meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n\
         <title>Level 0 crops</title>\n<style>\n\
         body{font:14px/1.4 system-ui,sans-serif;margin:16px;background:#fff;color:#111}\n\
         figure{margin:0 0 24px}\n\
         img{width:100%;max-width:1560px;image-rendering:pixelated;display:block}\n\
         figcaption{margin-top:4px}\n\
         @media (prefers-color-scheme: dark){body{background:#111;color:#eee}}\n\
         </style></head><body>\n<h1>Level 0 crops</h1>\n\
         <p>Each strip is the same 256 pixel window after BC1: baseline, the provider's best \
         variant, ZL18 truth. Shown at twice the size with nearest-neighbour scaling.</p>\n",
    );
    let mut provider = "";
    for c in crops {
        if c.provider != provider {
            provider = &c.provider;
            let _ = writeln!(s, "<h2>{provider}</h2>");
        }
        let _ = writeln!(
            s,
            "<figure><img src=\"crops/{}\" alt=\"{} {}\" loading=\"lazy\">\
             <figcaption>{} ({}): baseline | {} | truth. SSIM {:.4} to {:.4}</figcaption></figure>",
            c.file,
            c.provider,
            c.location,
            c.location,
            c.content,
            VARIANTS[c.variant].name,
            c.ssim_base,
            c.ssim_best
        );
    }
    s.push_str("</body></html>\n");
    s
}

#[cfg(test)]
mod tests {
    use super::*;

    fn row(location: &str, variant: usize, ssim: f64) -> Row {
        let scores = Scores {
            ssim,
            psnr: 30.0,
            ssim_linear: ssim,
            butteraugli: 1.0,
        };
        Row {
            provider: "p".to_string(),
            location: location.to_string(),
            content: "town".to_string(),
            synthetic: true,
            quality: Some(75),
            subsampling: Some("4:2:0".to_string()),
            variant,
            pre: scores,
            post: scores,
            filter_ms: 1.0,
            bc1_ms: 1.0,
        }
    }

    #[test]
    fn median_of_even_and_odd_counts() {
        assert_eq!(median(&[3.0, 1.0, 2.0]), 2.0);
        assert_eq!(median(&[4.0, 1.0, 2.0, 3.0]), 2.5);
    }

    #[test]
    fn the_best_variant_has_the_highest_mean_gain() {
        let mut rows = Vec::new();
        for (location, gain) in [("a", 0.02), ("b", 0.04)] {
            for v in 0..VARIANTS.len() {
                let ssim = 0.8 + if v == 5 { gain } else { -0.01 * v as f64 };
                rows.push(row(location, v, ssim));
            }
        }
        assert_eq!(best_variant(&rows, "p"), 5);
        let text = summary(&rows, "## Notes\n\nhand written");
        assert!(text.contains("| C deblock + usm 0.3 **(best)** | +0.0300 | +0.0300 |"));
        assert!(text.contains("hand written"));
        assert!(text.contains("The data is synthetic"));
    }

    #[test]
    fn the_busiest_window_is_where_the_detail_is() {
        let image = RgbaImage::from_fn(512, 512, |x, y| {
            let v = if x >= 256 && y >= 256 {
                ((x + y) % 2 * 200) as u8
            } else {
                90
            };
            Rgba([v, v, v, 255])
        });
        assert_eq!(busiest_window(&image), (256, 256));
    }

    #[test]
    fn a_triptych_puts_three_windows_side_by_side() {
        let a = RgbaImage::from_pixel(256, 256, Rgba([1, 1, 1, 255]));
        let b = RgbaImage::from_pixel(256, 256, Rgba([2, 2, 2, 255]));
        let c = RgbaImage::from_pixel(256, 256, Rgba([3, 3, 3, 255]));
        let out = triptych([&a, &b, &c], 0, 0);
        assert_eq!(out.dimensions(), (784, 256));
        assert_eq!(out.get_pixel(0, 0)[0], 1);
        assert_eq!(out.get_pixel(264, 0)[0], 2);
        assert_eq!(out.get_pixel(783, 255)[0], 3);
    }
}
